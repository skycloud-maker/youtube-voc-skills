# -*- coding: utf-8 -*-
"""문서들이 같은 것을 같은 말로 적고 있나.

★ 왜 만들었나 (sky 2026-09-07)
  「전체 문서에 통일되게 같은 내용들이 문제없이 기록되었는지 등 작업을
    해야되지 않을까요?」

  맞는 지적이다. 이 폴더에는 같은 사안을 말하는 문서가 여럿이다 —
  로드맵 · 반영대기 · 7차 대장 · 변경원장 · 안 하기로 한 것 · 동결규칙 ·
  오류대장 · 인계메모. 한 곳만 고치면 **다음 사람이 딴 문서를 보고 딴소리를 한다.**

  실제로 2026-09-07 에 E-1 을 「영구 종결」 로 정했는데, 그 전까지
  여섯 문서가 「다음 엔진 개정 때 고친다」 고 적고 있었다.

무엇을 보나
-----------
① 낡은 말   더 이상 사실이 아닌 문장이 정본 문서에 남아 있나
② 새 말     이번에 정한 것이 있어야 할 문서에 다 들어갔나

★ 옛 기록은 **지우지 않는다.** 그때 그렇게 정했다는 것이 사실이기 때문이다.
  대신 바로 아래 줄에 **「그 뒤 어떻게 됐는지」** 를 붙인다.
  이 검사는 그 뒤 이야기가 붙어 있으면 통과시킨다.

쓰는 법
-------
    python 문서_한말_검사.py            # 본다
    python 문서_한말_검사.py --자세히     # 걸린 줄을 다 편다

어긋나면 종료코드 1 이다 (`마무리_이력정리.py` 가 이걸 본다).

★ 새 판을 닫을 때는 아래 「말」 목록을 손으로 갱신한다.
  도구가 대신 못 쓴다 — 무엇이 바뀌었는지는 사람이 안다.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent
자세히 = "--자세히" in sys.argv

# 정본으로 보는 문서. 판 사본·작업이력·구버전은 안 본다
def 정본문서() -> list[Path]:
    문서 = sorted(p for p in 뿌리.glob("*.md"))
    문서.append(뿌리 / "_판독패키지" / "1a_기준문서_정본_1부.md")
    return [p for p in 문서 if p.is_file()]


# ── ① 더 이상 사실이 아닌 말 ─────────────────────────────
#    (찾을 것, 왜 낡았나, 뒤 이야기가 붙었는지 볼 표시)
낡은말 = [
    (r"보정요청\s*①②\s*회의", "3건 다 2026-09-07 에 닫혔다", None),
    (r"E-1~E-3 을 한 번에 풀", "엔진을 안 연다", None),
    (r"E-2 는 sky 결정으로 보류", "화면 파생 칸에서 해결했다", None),
    (r"보정요청 ②.*안 됐다", "닫혔다", None),
    (r"보정요청 ③.*안 됐다", "닫혔다", None),
    (r"「기타」 5종 정리", "「기타(로봇청소기)」 1행만 남았다", None),
    (r"3,916행 중 570행이 빈칸", "topic_group 빈칸은 0 이다", None),
    (r"다음 엔진 개정 때\s+Y 조건을 좁힌다", "E-1 은 영구 종결이다",
     "2026-09-07 에 뒤집혔다"),
]

# ── ② 이번에 정한 것이 들어가 있어야 할 자리 ──────────────
있어야 = [
    ("01_로드맵_CURRENT.md", "엔진을 열지 않고 다 닫았다"),
    ("28_대시보드_반영대기_목록.md", "영구 종결. 안 고친다"),
    ("29_7차_해결_미해결_대장.md", "남은 실작업은 이것 하나뿐"),
    ("90_변경원장_LEDGER.md", "7차 정리 — 엔진을 열지 않고"),
    ("91_결정사항_안하기로_한_것.md", "E-1 `review_required` 의 Y 조건"),
    ("92_동결운영규칙.md", "7차 — **엔진을 열지 않는다**"),
    ("93_오류발견대장.md", "7차 정리 — 여섯 건을 한 번에"),
    ("95_진행중_인계메모_20260827.md", "남은 실작업은 이것 하나뿐"),
    ("_판독패키지/1a_기준문서_정본_1부.md", "제품 구독·렌탈 서비스에만"),
    # ★ 2026-09-18 — 같은 기준서가 `21a_` 라는 다른 이름으로 뿌리·정본에도 있다.
    #   위 한 벌만 보다가 나머지 4벌이 옛판인 것을 못 잡았다. 쌍둥이도 본다.
    ("21a_기준문서_정본_1부.md", "제품 구독·렌탈 서비스에만"),
    ("_정본/최신/21a_기준문서_정본_1부.md", "제품 구독·렌탈 서비스에만"),
]


def main() -> int:
    문서 = 정본문서()
    탈 = 0
    print("=" * 66)
    print("  문서가 같은 말을 하나 — 정본 %d개" % len(문서))
    print("=" * 66)
    print()
    # ★ 2026-09-08 — 문서를 하나도 못 찾았는데 ① 이 「없음」 이라고 하면
    #   읽는 사람은 통과로 본다. 못 찾은 것은 통과가 아니다.
    #   (같은 함정을 「아무도 안 채우는 칸」 검사에서 먼저 잡았다)
    if len(문서) < 5:
        print("  ★ 정본 문서를 %d개밖에 못 찾았습니다 — **검사를 못 했습니다.**" % len(문서))
        print("     이 파일은 `outputs/voc_secondary/` 에서 돌려야 합니다.")
        print("     지금 자리: %s" % 뿌리)
        return 1

    print("  ① 더 이상 사실이 아닌 말이 남았나")
    for 패, 왜, 뒷이야기 in 낡은말:
        걸림 = []
        for p in 문서:
            줄들 = p.read_text(encoding="utf-8", errors="replace").splitlines()
            for i, l in enumerate(줄들):
                if not re.search(패, l):
                    continue
                # 옛 기록에 뒤 이야기가 붙어 있으면 통과
                뒤 = " ".join(줄들[i + 1:i + 3])
                if 뒷이야기 and 뒷이야기 in 뒤:
                    continue
                걸림.append((p.name, i + 1, l.strip()))
        if 걸림:
            탈 += len(걸림)
            print("     ★ %-30s — %s" % (패[:30], 왜))
            for n, i, l in (걸림 if 자세히 else 걸림[:3]):
                print("        %s:%d  %s" % (n, i, l[:72]))
        else:
            print("     · %-30s 없음" % 패[:30])

    print()
    print("  ② 이번에 정한 것이 다 들어갔나")
    for 이름, 말 in 있어야:
        p = 뿌리 / 이름
        있 = p.is_file() and 말 in p.read_text(encoding="utf-8", errors="replace")
        print("     %s %-34s %s" % ("·" if 있 else "★", 이름[:34], 말[:28]))
        if not 있:
            탈 += 1

    print()
    print("=" * 66)
    if 탈:
        print("  ★ 어긋난 곳 %d — 문서마다 딴소리를 합니다" % 탈)
        print()
        print("  고치는 법")
        print("    · 낡은 말은 지우거나, 옛 기록이면 **바로 아래에** 뒤 이야기를 붙이십시오")
        print("    · 이번 판에서 정한 것이 빠진 문서에는 그 말을 넣으십시오")
        print("    · 새 판을 닫을 때는 이 파일 위 「낡은말」·「있어야」 를 손으로 갱신합니다")
        return 1
    print("  · 문서가 다 같은 말을 합니다")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
