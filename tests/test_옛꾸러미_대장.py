# -*- coding: utf-8 -*-
"""옛 꾸러미에서 **안 옮긴 것**을 세는 대장이 살아 있는가 (2026-10-29).

★ 왜 이 시험이 있나 — sky 물음 2026-10-29
    「왜 누락이 계속 생기는지 모르겠네요」

  재어 보니 **옮기다 글을 줄인 적은 없었다.** 출처 기록 네 벌이 지문으로
  「옮긴 것이 변하지 않았음」 을 지킨다. **그런데 그 기록은 「옮긴 것」 만 센다** —
  「안 옮긴 것」 을 세는 자리가 없었으니 빠진 것은 검사에 걸릴 수가 없었다.
  검사기가 「못 찾음」 을 「없음」 으로 돌려주던 것과 **같은 병이 한 층 위에** 있었다.

  → `tools/옛꾸러미_대장.py` 가 옛 꾸러미 쪽에서 세어 `docs/옛꾸러미_목록.json` 에 적고,
    이 시험이 **그 수가 늘지 못하게** 지킨다. 수는 줄어들 수만 있다.

★ 옛 저장소(`paths.py` 의 `옛저장소`)는 **읽기만 하고**, 없는 컴퓨터도 있다. 그래서 이 시험은
  **저장소에 담긴 목록 파일**을 본다 — 옛 저장소를 읽지 않는다.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

_여기 = Path(__file__).resolve().parent
sys.path.insert(0, str(_여기.parent / "plugin" / "shared"))
from paths import REPO  # noqa: E402

목록자리 = REPO / "docs" / "옛꾸러미_목록.json"
까닭글 = REPO / "docs" / "옛꾸러미_대장.md"

# ★ 2026-10-29 에 처음 세어 못 박은 수. **줄일 수만 있다.**
#   늘려야 할 일이 생기면 그것은 「누락을 덮는 일」 이므로, 늘리기 전에 sky 에게 묻는다.
못박은_아직안봤다 = 114


@pytest.fixture(scope="module")
def 목록():
    assert 목록자리.is_file(), (
        "못 찾음: %s — 옛 꾸러미 대장이 없다. `python tools/옛꾸러미_대장.py` 를 돌리십시오.\n"
        "  (이 파일이 없으면 「안 옮긴 것」 을 세는 자리가 없어진다 — 통과가 아니다)" % 목록자리)
    return json.loads(목록자리.read_text(encoding="utf-8"))


def test_대장이_있고_셈이_맞는다(목록):
    """네 칸의 합이 센 파일 수와 같아야 한다 — 어느 칸에도 안 들어간 파일이 없다."""
    수 = 목록["수"]
    assert set(수) == {"그대로있다", "고쳤다", "안옮겼다", "아직안봤다"}, sorted(수)
    assert sum(수.values()) == 목록["센_파일수"], (
        "센 파일 %d개인데 칸의 합이 %d다 — 어디에도 안 들어간 파일이 있다"
        % (목록["센_파일수"], sum(수.values())))
    assert 목록["센_파일수"] > 0, "하나도 못 셌다 — 「못 찾음」 은 통과가 아니다"


def test_아직_안_본_것이_늘지_않았다(목록):
    """★ 이것이 이 시험의 알맹이다. **늘면 실패한다.**

    늘었다는 것은 ① 옛 꾸러미에 있는데 안 가져온 것이 새로 드러났거나
    ② 까닭을 적어 둔 줄이 지워졌다는 뜻이다. 둘 다 그냥 넘길 일이 아니다.
    """
    아직 = 목록["수"]["아직안봤다"]
    assert 아직 <= 못박은_아직안봤다, (
        "「아직 안 봤다」 가 %d개에서 %d개로 **늘었다.**\n"
        "  옮기거나, 안 옮길 까닭을 docs/옛꾸러미_대장.md 에 적으십시오.\n"
        "  수를 그냥 올려 못 박는 것은 **누락을 덮는 일**입니다 — sky 에게 먼저 물으십시오."
        % (못박은_아직안봤다, 아직))
    assert len(목록["아직안봤다"]) == 아직, "목록과 수가 다르다"


def test_줄었으면_못박은_수도_같이_내린다(목록):
    """★ 수가 줄었는데 못 박은 수를 그대로 두면, 다시 늘어도 안 걸린다.

    그러면 이 가드는 **느슨해진 채로 살아 있는 척**을 한다. 줄였으면 같이 내린다.
    """
    아직 = 목록["수"]["아직안봤다"]
    assert 아직 == 못박은_아직안봤다, (
        "「아직 안 봤다」 가 %d개로 줄었다 — 이 파일의 `못박은_아직안봤다` 도 %d 로 내리십시오.\n"
        "  (그대로 두면 다시 %d개까지 늘어도 안 걸린다)"
        % (아직, 아직, 못박은_아직안봤다))


def test_안_옮긴_것에는_까닭이_적혀_있다(목록):
    """「안 옮겼다」 칸에 들어가는 길은 **까닭 표에 걸리는 것** 하나뿐이다."""
    assert 까닭글.is_file(), "못 찾음: %s" % 까닭글
    글 = 까닭글.read_text(encoding="utf-8")
    assert 목록["수"]["안옮겼다"] > 0, "안 옮긴 것이 0개다 — 까닭 표가 안 읽혔을 수 있다"
    assert "안 옮긴 까닭" in 글, "까닭을 적는 절이 없다"
    assert "까닭 없이 무늬를 더하지 않는다" in 글, "까닭 없이 무늬를 더하지 말라는 말이 없다"


def test_뺀_자리를_수까지_적는다(목록):
    """★ 「뺀다」 고만 적고 수를 안 적으면, 무엇을 얼마나 뺐는지 아무도 모른다 (규율 2-2)."""
    뺀것 = 목록["뺀_자리"]
    assert 뺀것, "뺀 자리를 안 적었다"
    for 이름, v in 뺀것.items():
        assert "수" in v and "까닭" in v, "%s 에 수나 까닭이 없다" % 이름
        assert v["까닭"].strip(), "%s 를 뺀 까닭이 비었다" % 이름
    # 산출물을 뺀다는 말이 글에도 있어야 한다 (도구만 알고 사람은 모르면 안 된다)
    assert "산출물" in 까닭글.read_text(encoding="utf-8"), "산출물을 뺀다는 말이 글에 없다"


def test_재료가_든_자리는_빼지_않았다(목록):
    """★ 재료 폴더를 산출물과 섞어 빼면 **누락을 덮는다.**

    `_설계서/` · `_정본/` · `_인계/` · `_배포/` 는 글이 든 자리다. 빼면 안 된다.
    """
    뺀이름 = set(목록["뺀_자리"])
    for 재료 in ("_설계서", "_정본", "_인계", "_배포", "_판독패키지", "_제출"):
        assert 재료 not in 뺀이름, "재료가 든 자리를 셈에서 뺐다 — %s" % 재료
