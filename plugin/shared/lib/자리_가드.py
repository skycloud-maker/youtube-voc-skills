# -*- coding: utf-8 -*-
"""일하는 자리가 **꾸러미(저장소) 안인지** 보고, 안이면 멈추게 한다 (2026-11-04).

★ 왜 생겼나 — 결정 0013 으로 **AI 가 자리를 제안**하게 됐다. 사람이 안 보고 「네」 하면
  저장소 안이 자리로 잡힐 수 있고, 전에는 **아무도 막지 않았다**
  (`한줄_돌리기.py` 는 `판 = Path(a.판자리).resolve()` 뿐이었다).
  「저장소 밖에 차린다」 는 글로만 있었다 — 글은 안 읽히면 안 지켜진다
  (공통 규칙 「가드는 돌리는 자리에」).

★ 안이면 무엇이 나쁜가
  1차 엔진은 결과를 **자기 폴더 아래**(`data/` · `outputs/`)에 쓴다. 자리가 저장소 안이면
  결과가 저장소에 쏟아진다. 게다가 폴더 꾸러미장은 꾸러미를 **저장소에서 바로 읽는다**
  (`claude plugin install` 이 그렇게 말한다) — 즉 **지금 읽히고 있는 폴더에 결과를 붓는** 꼴이다.
  그 뒤 `판_묶기.py` 가 다시 묶으면 결과 파일이 꾸러미에 섞여 들어갈 수 있다.

★ 막는 범위 — **꾸러미 뿌리와 그 위 한 칸** 전체다.
  꾸러미 뿌리 = `.claude-plugin/plugin.json` 이 있는 폴더 (`<저장소>/plugin` 또는 `<푼 폴더>/plugin`).
  그 **위 한 칸**까지 막는 까닭 — 저장소 뿌리에는 `dist/` · `docs/` · `tests/` 가 있고,
  거기에 결과가 쌓이면 꾸러미를 묶을 때 섞인다. 「빈 폴더에 풀고」 라고 안내하는 뜻도 그것이다.

★ **빠져나갈 깃발을 두지 않는다.** 깃발이 있으면 AI 가 조용히 지나갈 수 있다.
  이것은 취향이 아니라 **규칙**이다 (sky 결정 0013 — 「사람이 정해야 하는 것은 제약뿐이고
  그건 규칙이지 선택이 아니다」).

★ **「못 찾음」 을 「없음」 으로 돌려주지 않는다.** 꾸러미 뿌리를 못 찾으면 막지 못한다는 뜻이고,
  그때는 **통과시키되 까닭을 적어 돌려준다** — 부르는 쪽이 그 말을 사람에게 보여 준다.
  조용히 통과하면 검사한 척이 된다.
"""
from __future__ import annotations

import sys
from pathlib import Path

__all__ = ["꾸러미뿌리", "저장소안인가", "자리_확인", "자리_확인하고_멈추기"]


def 꾸러미뿌리(여기: Path | None = None) -> Path | None:
    """울로 삼을 뿌리를 위로 올라가며 찾는다. 못 찾으면 None.

    ① `.claude-plugin/plugin.json` 이 있는 폴더 — 플러그인 꾸러미 (`<저장소>/plugin`).
    ② 없으면 `SKILL.md` 가 있는 폴더 — **낱개로 꾸린 스킬** (claude.ai 쪽 zip).

    ★ 2026-11-04 — ② 가 없으면 **낱개 꾸러미에서 가드가 아예 일하지 못했다.**
      거기엔 `plugin.json` 이 없어 「못 찾았다」 고 말하고 그냥 통과했다
      (`tests/test_build.py` 의 낱개 시험 넷이 그것을 드러냈다). 낱개로는
      `<스킬>/shared/lib/자리_가드.py` 꼴이라 위로 올라가면 `<스킬>/SKILL.md` 가 나온다.
    """
    여기 = (여기 or Path(__file__)).resolve()
    자리들 = (여기, *여기.parents)
    for d in 자리들:
        if (d / ".claude-plugin" / "plugin.json").is_file():
            return d
    for d in 자리들:
        if (d / "SKILL.md").is_file():
            return d
    return None


def _안에있나(자리: Path, 울: Path) -> bool:
    """자리가 울 그 자체이거나 울 아래인가.

    ★ 대소문자는 **`pathlib` 에 맡긴다.** 윈도 `WindowsPath` 는 경로를 대소문자 가리지 않고
      비교하고, 리눅스 `PosixPath` 는 가린다 — 각 운영체제의 파일 이름 규칙과 같다.
      ★ 2026-11-04 — 처음에는 `str(...).lower()` 로 억지로 맞췄다. **일부러 그 줄을 빼
        봤더니 시험이 그대로 통과**해서 쓸모없는 덧방패임을 알았다. 게다가 리눅스에서는
        **틀린 답**을 만든다 (`a/` 와 `A/` 가 다른 자리인데 같다고 한다).
        가장 단순한 것으로 되돌렸다.
    """
    try:
        a, b = 자리.resolve(), 울.resolve()
    except OSError:
        return False
    return a == b or b in a.parents


def 저장소안인가(자리: Path, 뿌리: Path | None = None,
             찾는자리: Path | None = None) -> tuple[bool, Path | None, str]:
    """(막아야 하나, 걸린 울, 왜) — 뿌리를 못 찾으면 (False, None, 까닭).

    ★ `찾는자리` — 뿌리를 **어디서부터 올라가며** 찾을지. 시험이 「못 찾는 경우」 를
      실제로 태워 볼 수 있어야 하므로 받는다 (`뿌리=None` 만으로는 스스로 다시 찾아
      「못 찾음」 을 흉내 낼 수 없었다 — 2026-11-04 시험이 잡았다).
    """
    if 뿌리 is None:
        뿌리 = 꾸러미뿌리(찾는자리)
    if 뿌리 is None:
        return (False, None, "꾸러미 뿌리(.claude-plugin/plugin.json)를 못 찾아 "
                             "저장소 안인지 **확인하지 못했습니다** — 막지 않았습니다")
    for 울, 뭐 in ((뿌리, "꾸러미 폴더"), (뿌리.parent, "저장소(또는 푼 폴더) 뿌리")):
        if _안에있나(자리, 울):
            return (True, 울, 뭐)
    return (False, None, "")


def 권할자리(울: Path) -> Path:
    """막았을 때 **대신 쓰라고 권할 자리** — 반드시 울 밖이어야 한다.

    ★ 2026-11-04 — 처음에는 `울.parent.parent / "VoC_판"` 로만 냈다. 그런데 작업 폴더
      (`<저장소>/.claude/worktrees/<이름>`)에서 돌리면 그 값이 `<저장소>/.claude/VoC_판`
      — **울 안**이 나왔다. 「저장소 밖으로 가라」 면서 저장소 안을 권한 것이다.
      그래서 **권하기 전에 스스로 대 보고**, 울 안이면 드라이브 뿌리로 내린다.
    """
    for 후보 in (울.parent.parent / "VoC_판", 울.parent / "VoC_판"):
        if _안에있나(후보, 울):
            continue
        # ★ `.claude` 아래는 권하지 않는다 — 작업 폴더(worktree)로 돌리면 울이 작업 폴더라
        #   `<저장소>/.claude/VoC_판` 이 「울 밖」 으로 보이지만 **저장소 안**이다.
        if any(x.lower() == ".claude" for x in 후보.parts):
            continue
        return 후보
    return Path(울.anchor or "C:/") / "VoC_판"      # 마지막 수단 — 드라이브 뿌리


def 자리_확인(자리: Path, 이름: str = "자리", 뿌리: Path | None = None,
             찾는자리: Path | None = None) -> tuple[bool, list[str]]:
    """(써도 되나, 사람에게 보여 줄 말들)."""
    막아야, 울, 왜 = 저장소안인가(자리, 뿌리, 찾는자리)
    if 막아야:
        권 = 권할자리(울)
        return (False, [
            "✗ %s 를 **저장소 안**으로 잡았습니다 — 여기서 멈춥니다." % 이름,
            "    준 자리 : %s" % 자리,
            "    걸린 울 : %s  (%s)" % (울, 왜),
            "  까닭 — 1차 엔진은 결과를 자기 폴더 아래(data/ · outputs/)에 씁니다.",
            "         저장소 안이면 결과가 저장소에 쌓이고, 꾸러미는 이 폴더에서 **바로 읽히므로**",
            "         읽히는 중인 폴더에 결과를 붓는 꼴이 됩니다. 다시 묶을 때 섞입니다.",
            "  이렇게 하십시오 — **저장소 밖**으로 잡습니다. 예: %s\\<연-월>_<검색어>" % 권,
        ])
    if 왜:                      # 뿌리를 못 찾았다 — 통과시키되 말해 준다
        return (True, ["  ★ %s" % 왜])
    return (True, [])


def 자리_확인하고_멈추기(자리: Path, 이름: str = "자리", 뿌리: Path | None = None,
                   찾는자리: Path | None = None, 종료코드: int = 2) -> None:
    """못 쓰는 자리면 말하고 **프로그램을 끝낸다** (`SystemExit`)."""
    괜찮, 말들 = 자리_확인(자리, 이름, 뿌리, 찾는자리)
    for l in 말들:
        print(l)
    if not 괜찮:
        sys.exit(종료코드)
